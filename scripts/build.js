#!/usr/bin/env node
/*
 * svg-codes build script. Own code, MIT (see LICENSE).
 *
 * Joins the vendor files, adapters and unified API from src/ into one
 * plain-script file: dist/svg-codes.js
 *
 * - No dependencies. Plain Node.
 * - Strips import/export statements and wraps everything in one function,
 *   so the only global left behind is `SvgCodes`.
 * - Keeps the original copyright headers inside each vendor file.
 *
 * Usage:  node scripts/build.js
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT_DIR = path.join(ROOT, 'dist');
const OUT_FILE = path.join(OUT_DIR, 'svg-codes.js');

/* Dependency order: every file may only import files listed before it. */
const FILES = [
    'vendor/qrcode.js',
    'vendor/datamatrix.js',
    'vendor/barcode.js',
    'adapters/common.js',
    'adapters/qr.js',
    'adapters/datamatrix.js',
    'adapters/barcode.js',
    'index.js'
];

const BANNER = [
    '/*!',
    ' * svg-codes: QR Code, Data Matrix and Code 128 as SVG (single-file build).',
    ' * Generated by scripts/build.js from src/. Do not edit this file by hand.',
    ' *',
    ' * Own code: MIT, see LICENSE.',
    ' * Includes generators by datalog (MIT): qrcode-svg, datamatrix-svg, barcode-svg.',
    ' * Their copyright headers are kept below. See THIRD_PARTY_NOTICES.md.',
    ' *',
    ' * Usage: <script src="svg-codes.js"></script>',
    ' *        const svg = SvgCodes.generate({ type: "qr", msg: "Hello" });',
    ' */',
    ''
].join('\n');

const FOOTER = [
    '',
    '/* ---------- Public API ---------- */',
    '',
    'var api = {',
    '    generate: generate,',
    '    toString: toSvgString,',
    '    toDataURL: toDataURL,',
    '    toPNG: toPNG,',
    '    TYPES: TYPES,',
    '    CodeError: CodeError,',
    '    QRCode: QRCode,',
    '    DATAMatrix: DATAMatrix,',
    '    BARCode: BARCode',
    '};',
    '',
    "if (typeof module === 'object' && module && module.exports) {",
    '    module.exports = api;',
    '}',
    '',
    'global.SvgCodes = api;',
    ''
].join('\n');

function fail(message) {
    console.error('Build failed: ' + message);
    process.exit(1);
}

function read(rel) {
    const file = path.join(SRC, rel);
    if (!fs.existsSync(file)) fail('missing file src/' + rel);
    return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

/* Every import must point to a listed file that comes earlier in FILES. */
function checkImports(rel, code, position) {
    const re = /^import\s[^;]*?from\s+['"]([^'"]+)['"]/gm;
    let m;

    while ((m = re.exec(code)) !== null) {
        const target = path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1]));
        const at = FILES.indexOf(target);

        if (at === -1) fail('src/' + rel + ' imports "' + m[1] + '", which is not in the build list.');
        if (at >= position) fail('src/' + rel + ' imports "' + m[1] + '", which comes later in the build order.');
    }
}

function strip(code) {
    return code
        .replace(/^'use strict';[ \t]*\n/gm, '')
        .replace(/^import\s[^;]*;[ \t]*\n?/gm, '')
        .replace(/^export\s*\{[^}]*\};?[ \t]*\n?/gm, '')
        .replace(/^export default [^\n]*\n?/gm, '')
        .replace(/^export\s+(class|function|const|let|var|async)\s/gm, '$1 ');
}

function build() {
    const parts = [];

    FILES.forEach(function (rel, i) {
        const original = read(rel);
        checkImports(rel, original, i);

        const body = strip(original).trim();
        parts.push('/* ---------- src/' + rel + ' ---------- */\n\n' + body + '\n');
    });

    const output =
        BANNER +
        '(function (global) {\n' +
        "'use strict';\n\n" +
        parts.join('\n') +
        FOOTER +
        "})(typeof globalThis !== 'undefined' ? globalThis : typeof self !== 'undefined' ? self : this);\n";

    /* Nothing module-only may be left over. */
    const left = output.match(/^[ \t]*(import|export)\s.*$/m);
    if (left) fail('an import/export statement is still in the output: ' + left[0].trim());

    /* The result must at least parse as a plain script. */
    try {
        new vm.Script(output, { filename: 'svg-codes.js' });
    } catch (e) {
        fail('the combined file does not parse: ' + e.message);
    }

    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(OUT_FILE, output);

    const kb = (Buffer.byteLength(output) / 1024).toFixed(2);
    console.log('Built dist/svg-codes.js (' + kb + ' KB) from ' + FILES.length + ' files.');
}

build();